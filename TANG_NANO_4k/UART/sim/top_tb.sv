`timescale 1ns/1ps

module top_tb;

reg clk;
reg rst_n;

wire tx;

////////////////////////////////////////////////////
// DUT
////////////////////////////////////////////////////

top DUT(

    .clk(clk),
    .rst_n(rst_n),
    .tx(tx)

);

////////////////////////////////////////////////////
// Clock
////////////////////////////////////////////////////

initial begin

    clk = 0;

    forever #5 clk = ~clk;

end

////////////////////////////////////////////////////
// VCD
////////////////////////////////////////////////////

initial begin

    $dumpfile("sim/top.vcd");
    $dumpvars(0,top_tb);

end

////////////////////////////////////////////////////
// Reset
////////////////////////////////////////////////////

initial begin

    rst_n = 0;

    #20;

    rst_n = 1;

    #2000;

    $finish;

end

////////////////////////////////////////////////////
// Monitor
////////////////////////////////////////////////////

always @(posedge clk) begin

    $display("Time=%0t TX=%b Address=%0d Data=%h Busy=%b Done=%b",
        $time,
        tx,
        DUT.rom_addr,
        DUT.tx_data,
        DUT.tx_busy,
        DUT.tx_done);

end

endmodule